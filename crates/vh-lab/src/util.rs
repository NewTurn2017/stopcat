//! 시각·run id·파일 쓰기·sha256.

use std::fs::{self, File, OpenOptions};
use std::io::{self, Read, Write};
use std::path::Path;
use std::time::{SystemTime, UNIX_EPOCH};

use serde::Serialize;

pub fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

/// `yyyymmddHHMMSS-<16 hex>`(현지 시각 + /dev/urandom 8바이트).
pub fn new_run_id() -> io::Result<String> {
    let mut rnd = [0u8; 8];
    File::open("/dev/urandom")?.read_exact(&mut rnd)?;
    let secs = (now_ms() / 1000) as libc::time_t;
    // SAFETY: tm은 0으로 채운 지역 값, localtime_r는 tm에만 쓴다.
    let mut tm: libc::tm = unsafe { std::mem::zeroed() };
    // SAFETY: secs·tm 모두 유효한 지역 변수 포인터.
    unsafe { libc::localtime_r(&secs, &mut tm) };
    let hex: String = rnd.iter().map(|b| format!("{b:02x}")).collect();
    Ok(format!(
        "{:04}{:02}{:02}{:02}{:02}{:02}-{hex}",
        tm.tm_year + 1900,
        tm.tm_mon + 1,
        tm.tm_mday,
        tm.tm_hour,
        tm.tm_min,
        tm.tm_sec
    ))
}

pub fn write_json(path: &Path, value: &impl Serialize) -> io::Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    let mut body = serde_json::to_vec_pretty(value).map_err(io::Error::other)?;
    body.push(b'\n');
    fs::write(path, body)
}

pub fn write_jsonl<T: Serialize>(path: &Path, rows: &[T]) -> io::Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    let mut f = OpenOptions::new()
        .create(true)
        .write(true)
        .truncate(true)
        .open(path)?;
    for r in rows {
        serde_json::to_writer(&mut f, r).map_err(io::Error::other)?;
        f.write_all(b"\n")?;
    }
    Ok(())
}

pub fn sha256_file(path: &Path) -> io::Result<String> {
    Ok(sha256_hex(&fs::read(path)?))
}

